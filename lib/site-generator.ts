import type { GeneratedProject, PatternAnalysis, SitePlan } from "@/lib/types";

export function generateProject(plan: SitePlan, patterns: PatternAnalysis): GeneratedProject {
  const repoName = plan.brandName.toLowerCase().replace(/[^a-z0-9]+/g, "-");

  return {
    repoName,
    files: [
      {
        path: "package.json",
        content: JSON.stringify(
          {
            scripts: {
              dev: "next dev",
              build: "next build",
              start: "next start"
            },
            dependencies: {
              "@next/font": "latest",
              next: "latest",
              react: "latest",
              "react-dom": "latest",
              "lucide-react": "latest"
            },
            devDependencies: {
              typescript: "latest",
              tailwindcss: "latest",
              "@types/node": "latest",
              "@types/react": "latest"
            }
          },
          null,
          2
        )
      },
      {
        path: "app/page.tsx",
        content: pageTemplate(plan, patterns)
      },
      {
        path: "app/layout.tsx",
        content: layoutTemplate(plan)
      },
      {
        path: "app/globals.css",
        content: cssTemplate(plan)
      },
      {
        path: "components/Pricing.tsx",
        content: pricingTemplate(plan)
      },
      {
        path: "README.md",
        content: `# ${plan.brandName}\n\nGenerated by AI Website Factory from pattern intelligence, not copied source code.\n\n## Positioning\n\n${plan.headline}\n\n## QA notes\n\n- CTA above fold: ${patterns.ctaPosition}\n- Flow: ${patterns.sectionFlow.join(" -> ")}\n- Rhythm: ${patterns.visualRhythm}\n`
      }
    ]
  };
}

function pageTemplate(plan: SitePlan, patterns: PatternAnalysis) {
  return `import { ArrowRight, CheckCircle2, Factory, Radar, Rocket } from "lucide-react";
import { Pricing } from "@/components/Pricing";

const workflow = ${JSON.stringify(plan.siteStructure.find((section) => section.id === "workflow")?.content || [], null, 2)};

export default function Home() {
  return (
    <main>
      <nav className="nav">
        <strong>${plan.brandName}</strong>
        <a href="#pricing">Pricing</a>
      </nav>

      <section className="hero">
        <div>
          <p className="eyebrow">${plan.industry} for ${plan.targetAudience}</p>
          <h1>${plan.headline}</h1>
          <p>${plan.subheadline}</p>
          <a className="button" href="#pricing">
            Start the factory <ArrowRight size={18} />
          </a>
        </div>
        <aside className="preview" aria-label="Generated site quality score">
          <span>QA ready</span>
          <strong>94</strong>
          <p>${patterns.visualRhythm}</p>
        </aside>
      </section>

      <section className="band">
        <div className="metric"><Radar /> Trend scan</div>
        <div className="metric"><Factory /> Original plan</div>
        <div className="metric"><Rocket /> Deployable code</div>
      </section>

      <section className="grid">
        {workflow.map((step) => (
          <article key={step}>
            <CheckCircle2 />
            <h2>{step}</h2>
            <p>Built as one focused step in the production pipeline.</p>
          </article>
        ))}
      </section>

      <Pricing />
    </main>
  );
}
`;
}

